st.markdown(
    """
باختبارات جذر الوحدة (:gray-badge[unit root tests]). أشهرها ثلاثة، وتفاصيلها
في صفحة **الاختبارات القبلية**، لكن الفكرة العامة:

| الاختبار | فرضية العدم H₀ | القرار |
|---|---|---|
| **ADF** — Augmented Dickey-Fuller | يوجد جذر وحدة، أي السلسلة غير ساكنة | رفض H₀ ← السلسلة ساكنة |
| **PP** — Phillips-Perron | يوجد جذر وحدة | رفض H₀ ← السلسلة ساكنة |
| **KPSS** | السلسلة ساكنة *(معكوس!)* | رفض H₀ ← السلسلة غير ساكنة |

:material/lightbulb: **نصيحة عملية:** استخدم ADF و KPSS معًا. إذا اتفقا، فالنتيجة
موثوقة. وإذا تعارضا، فأنت في منطقة رمادية — وهنا تحديدًا تظهر قيمة منهجية ARDL،
لأنها **تعمل بصرف النظر** عن كون المتغيّر I(0) أو I(1).
"""
)

