import streamlit as st

from lib.ui import definition, hero, intuition, rtl_css, signature, warn
from lib.viz import ardl_decomposition_chart, ecm_animation

rtl_css()

hero("نموذج تصحيح الخطأ", "Error Correction Model — كيف نجمع الأجلين في معادلة واحدة")

st.markdown(
    """
## المعضلة التي يحلّها

رأينا أن أمامنا خيارين سيئين:

- **المستويات فقط** ← خطر الانحدار الزائف.
- **الفروق فقط** ← نفقد معلومات التوازن طويل الأجل.

نموذج تصحيح الخطأ (ECM) يحلّ المعضلة بأناقة: **يضع الاثنين في معادلة واحدة**.
"""
)

st.markdown("## الصيغة")

st.latex(r"""
\underbrace{\Delta y_t}_{\text{التغيّر الآن}}
= \underbrace{\mu}_{\text{ثابت}}
+ \underbrace{\lambda\, y_{t-1} + \beta\, x_{t-1}}_{\text{جزء الأجل الطويل}}
+ \underbrace{\gamma\, \Delta x_t}_{\text{جزء الأجل القصير}}
+ u_t
""")

st.markdown(
    """
كل حدّ في هذه المعادلة له دور محدّد ومعنى اقتصادي واضح:
"""
)

st.plotly_chart(ardl_decomposition_chart(), width="stretch")

st.markdown("## المعامل الأهم في النموذج كلّه: λ")

definition(
    "سرعة التعديل — Speed of adjustment (λ)",
    "المعامل على المستوى المُبطَّأ للمتغيّر التابع $y_{t-1}$. "
    "يقيس <b>النسبة من الانحراف عن التوازن التي تُصحَّح في كل فترة</b>. "
    "يجب أن يكون <b>سالبًا</b> ليكون النظام مستقرًا، "
    "وتقع قيمته المعقولة بين $-1$ و $0$.",
)

intuition(
    "تخيّل <b>منظّم حرارة</b> (ثرموستات) ضُبط على 22 درجة.<br><br>"
    "إذا ارتفعت حرارة الغرفة إلى 26 درجة، فالانحراف = 4 درجات.<br><br>"
    "لو كان <b>λ = −0.25</b>، فالمنظّم يزيل ربع الانحراف كل ساعة: "
    "بعد ساعة يبقى 3 درجات، وبعد ساعتين 2.25، وهكذا. التصحيح بطيء.<br><br>"
    "ولو كان <b>λ = −0.80</b>، فالمنظّم قوي: يزيل 80% فورًا، فلا يبقى بعد "
    "ساعة إلا 0.8 درجة. التصحيح سريع.<br><br>"
    "<b>وإذا كان λ موجبًا</b>، فالمنظّم معطوب: كلما ارتفعت الحرارة زادها أكثر! "
    "النظام ينفجر ولا يوجد توازن.",
    term="المثال الأوضح",
)

st.markdown("### شاهد التصحيح وهو يحدث")

st.markdown(
    "اضغط **شغّل** لترى كيف يُغلق الانحراف عن التوازن بثلاث سرعات مختلفة. "
    "لاحظ أن الخط الأخضر (λ = −0.70) يصل إلى الصفر بسرعة، بينما الأحمر "
    "(λ = −0.15) يحتاج عشرات الفترات."
)

st.plotly_chart(ecm_animation(), width="stretch")

cols = st.columns(3)
with cols[0]:
    st.metric("λ = −0.15", "نصف العمر ≈ 4.3 فترة",
              help="الزمن اللازم لإزالة نصف الانحراف")
with cols[1]:
    st.metric("λ = −0.35", "نصف العمر ≈ 1.6 فترة")
with cols[2]:
    st.metric("λ = −0.70", "نصف العمر ≈ 0.6 فترة")

st.caption(
    "نصف العمر يُحسب بالصيغة $\\; h = \\ln(0.5) / \\ln(1+\\lambda)$. "
    "إن كانت بياناتك سنوية، فـ λ = −0.35 يعني أن نصف الانحراف يزول في أقل من سنتين."
)

st.markdown("## من أين يأتي معامل الأجل الطويل؟")

st.markdown(
    """
هذه نقطة يخطئ فيها كثيرون. المعامل $\\beta$ في المعادلة **ليس** هو معامل
الأجل الطويل. لنشتقّه.

في حالة التوازن طويل الأجل، لا شيء يتغيّر: $\\Delta y_t = 0$ و $\\Delta x_t = 0$.
نضع ذلك في المعادلة:
"""
)

st.latex(r"0 = \mu + \lambda\, y_{t-1} + \beta\, x_{t-1}")

st.markdown("ثم نحلّ لإيجاد $y$:")

st.latex(r"""
y_{t-1} = -\frac{\mu}{\lambda} \;-\; \frac{\beta}{\lambda}\, x_{t-1}
\qquad\Longrightarrow\qquad
\boxed{\;\theta^{LR} = -\frac{\beta}{\lambda}\;}
""")

warn(
    "<b>معامل الأجل الطويل نسبة، وليس معاملًا مباشرًا.</b> "
    "ولهذا ثلاث نتائج عملية مهمة:<br>"
    "<ul>"
    "<li>خطؤه المعياري لا يُقرأ من جدول الانحدار، بل يُحسب بطريقة دلتا.</li>"
    "<li>إذا كان $\\lambda$ قريبًا من الصفر، فالمقام قريب من الصفر، "
    "والنسبة تصبح غير مستقرّة إطلاقًا.</li>"
    "<li>إشارة $\\theta$ تعتمد على إشارتي البسط والمقام معًا. "
    "بما أن $\\lambda < 0$، فإن $\\theta$ تأخذ إشارة $\\beta$ نفسها.</li>"
    "</ul>",
    term="نقطة حاسمة",
)

st.markdown("## حاسبة تفاعلية")

c1, c2 = st.columns(2)
with c1:
    lam = st.slider("λ — سرعة التعديل", -0.95, -0.02, -0.35, 0.01)
with c2:
    beta = st.slider("β — معامل المستوى المُبطَّأ لـ x", -1.0, 1.0, 0.09, 0.01)

theta = -beta / lam
half = __import__("math").log(0.5) / __import__("math").log(1 + lam)

m1, m2, m3 = st.columns(3)
m1.metric("معامل الأجل الطويل  θ = −β/λ", f"{theta:+.3f}")
m2.metric("نصف عمر الانحراف", f"{half:.2f} فترة")
m3.metric("نسبة التصحيح في الفترة الواحدة", f"{abs(lam)*100:.0f}%")

if abs(lam) < 0.10:
    st.warning(
        "λ قريب جدًا من الصفر. لاحظ كيف تقفز قيمة θ بشدة عند أي تغيير بسيط في β. "
        "هذه بالضبط حالة **التعريف الضعيف** التي تجعل فترات الثقة بطريقة دلتا "
        "غير موثوقة — وهو ما وثّقته المحاكاة الخامسة في الورقة. "
        "في هذه الحالة استخدم مجموعة Fieller.",
        icon=":material/warning:",
    )

st.markdown("## من ECM إلى ARDL")

st.markdown(
    """
ما رأيناه هنا هو أبسط صورة: ARDL(1,1). الصيغة العامة تضيف إبطاءات أكثر
للمتغيّر التابع وللمتغيرات المفسّرة:
"""
)

st.latex(r"""
\Delta y_{t} = \mu + \delta t + \lambda y_{t-1} + \sum_{k=1}^{K}\beta_k x_{k,t-1}
+ \sum_{j=1}^{p-1}\psi_j \Delta y_{t-j}
+ \sum_{k=1}^{K}\sum_{j=0}^{q_k-1}\gamma_{k,j}\,\Delta x_{k,t-j} + u_t
""")

st.markdown(
    """
وهذه هي **المعادلة (7)** في ورقة أريف وفوروكا. لا تدع كثرة الرموز تخيفك —
الفكرة نفسها تمامًا:

- $\\lambda y_{t-1} + \\sum \\beta_k x_{k,t-1}$ ← الأجل الطويل (مستويات مُبطَّأة).
- باقي الحدود ← الأجل القصير (فروق).
- $\\mu$ و $\\delta t$ ← المكوّنات الحتمية.

الآن أنت تملك كل ما يلزم لفهم المنهجيتين الأصليتين. لنبدأ بزيلنر.
"""
)

signature()
