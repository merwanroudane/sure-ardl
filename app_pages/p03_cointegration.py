    "**نظرية التمثيل لجرانجر (1987):** إذا كان المتغيّران متكاملين تكامُلًا "
    "مشتركًا، فلا بد أن يوجد تمثيل لهما على صورة **نموذج تصحيح الخطأ**، والعكس "
